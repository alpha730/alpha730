// Builds every SVG in assets/ and README.md from profile.config.json, in the
// "comic book x Game of Thrones" style. Pixel art comes from scripts/art/pixel/
// (made by the dev-only generators in scripts/art/); text is drawn as paths.
//
// Minimum text sizes keep real text >= 10px when shown 330px wide (GitHub on a phone):
// 800-wide panels use a narrow-width layout; 392-wide cards use >= 13px.
import { readFile, writeFile, mkdir, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { heroSvg } from "./lib/comic-hero.mjs";
import { chaptersTitle, chapterCard, chain } from "./lib/comic-cards.mjs";
import { footer } from "./lib/comic-footer.mjs";
import { watchSvg, langSvg, activitySvg } from "./lib/live.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cfg = JSON.parse(await readFile(path.join(root, "profile.config.json"), "utf8"));
const out = path.join(root, "assets");
await mkdir(out, { recursive: true });
const write = (name, svg) => writeFile(path.join(out, name), svg);
const { person, missions } = cfg;
const repoUrl = (m) => `https://github.com/${person.github}/${m.repo}`;

// ---------- README.md, generated so its text always matches the art ----------
const attr = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const img = (src, alt, width) => `<img src="${src}" alt="${attr(alt)}" width="${width}">`;
const chapterAlt = (m) => `Chapter ${m.banner}. ${m.artAlt}. ${m.blurb} Stack: ${m.stack.join(", ")}.`;
const cardLink = (m, i) => `<a href="${repoUrl(m)}">${img(`assets/chapter-${i + 1}.svg`, chapterAlt(m), 392)}</a>`;
const titleCase = (s) => s.toLowerCase().replace(/\b([a-z])/g, (c) => c.toUpperCase()).replace(/\bIi+\b|\bIv\b/gi, (r) => r.toUpperCase()).replace(/'S\b/g, "'s");

function readme() {
  const rows = [];
  for (let i = 0; i < missions.length; i += 2) {
    const pair = [cardLink(missions[i], i)];
    if (!missions[i].result) pair.push("<!-- TODO: add metric -->");
    if (missions[i + 1]) {
      pair.push(cardLink(missions[i + 1], i + 1));
      if (!missions[i + 1].result) pair.push("<!-- TODO: add metric -->");
    }
    rows.push(pair.join("\n"));
  }
  const chapterLinks = missions.map((m) => `<a href="${repoUrl(m)}">${attr(titleCase(m.banner))}</a>`).join(" · ");
  return `<!-- Generated by scripts/build.mjs from profile.config.json. Edit the config, then run npm run build. -->
<div align="center">

${img("assets/hero.svg", `Comic cover: The Northern Realm, issue 01, @${person.github}. Pixel-art splash of a pale heart tree with blood-red leaves in the snow and a raven crossing the moon. Meanwhile, in the north... ${person.name}. ${person.role}.`, 800)}

${img("assets/chapters-title.svg", "The Four Chapters", 800)}

${rows.join("\n\n")}

${img("assets/chain.svg", "The Maester's Chain, one link for each discipline. " + cfg.chain.map((r) => `${titleCase(r.label)}: ${r.items.join(", ")}.`).join(" "), 800)}

${img("assets/watch.svg", "The Long Watch: public contributions in the last 12 months, with one torch per week on a brick wall, lit on weeks with commits. Public contributions only.", 800)}

${img("assets/languages.svg", "Top languages by share of code across public repositories", 392)}
${img("assets/activity.svg", "Weekly public contributions over the last 26 weeks", 392)}

${img("assets/footer.svg", `Send a raven: the name ${person.github} in giant dry-brush ink letters with a raven, a wolf pup, a hooded watchman and a small dragon sitting on them. © 2026 ${person.name}.`, 800)}

<p><a href="${person.portfolio}"><b>Portfolio</b></a> · <a href="https://github.com/${person.github}"><b>GitHub</b></a></p>
<p>${chapterLinks}</p>

</div>
`;
}

await write("hero.svg", heroSvg(person));
if (process.argv.includes("--only=hero")) {
  console.log("hero built");
  process.exit(0);
}
await write("chapters-title.svg", chaptersTitle());
for (const [i, m] of missions.entries()) await write(`chapter-${i + 1}.svg`, chapterCard(m, i));
await write("chain.svg", chain(cfg));
await write("footer.svg", footer(cfg));

// Live-stat panels: re-rendered from the last fetched data (assets/live-data.json,
// written by live-stats.mjs) so they follow design changes; placeholders until then.
// Older data files carry `streak.total` but no 52-week series: torches stay unlit.
let live = {};
try { live = JSON.parse(await readFile(path.join(out, "live-data.json"), "utf8")); } catch {}
const watch = live.watch ?? (live.streak ? { total: live.streak.total, weeks: null, date: live.streak.date } : null);
await write("watch.svg", watchSvg(watch));
await write("languages.svg", langSvg(live.languages ?? null));
await write("activity.svg", activitySvg(live.activity ?? null));

// assets from earlier designs
for (const old of ["header.svg", "realm.svg", "forge.svg", "streak.svg", "divider.svg", "typing.svg", "telemetry.svg", "instruments.svg"])
  await rm(path.join(out, old), { force: true });

await writeFile(path.join(root, "README.md"), readme());
console.log("assets + README built");
